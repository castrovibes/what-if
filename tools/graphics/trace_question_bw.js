/* global __dirname */
// Step 2 of 2 for the black-and-white vector question mark: traces the masks from
// make_question_bw.py with potrace (the pure-JS port) and writes
//   assets/graphics/question-mark-bw.svg        black ink over a white fill
//   assets/graphics/question-mark-bw-lines.svg  black ink only (transparent inside)
//   src/ui/questionMarkPath.ts                  the ink traced from the one-third-scale
//                                               mask, for the QuestionMark component
//
// Usage (install potrace in a scratch folder so it isn't added to the app's dependencies):
//   npm install potrace
//   NODE_PATH=<scratch>/node_modules node tools/graphics/trace_question_bw.js \
//     /tmp/mask-ink.png /tmp/mask-sil.png /tmp/mask-ink-small.png assets/graphics/question-mark-bw
const potrace = require('potrace');
const fs = require('fs');
const path = require('path');

const [, , inkPng, silPng, smallPng, outBase] = process.argv;
const base = { threshold: 128, turdSize: 60, optTolerance: 0.3, alphaMax: 1.0,
  turnPolicy: potrace.Potrace.TURNPOLICY_MINORITY };

function trace(file, extra) {
  return new Promise((resolve, reject) => {
    const p = new potrace.Potrace({ ...base, ...extra });
    p.loadImage(file, err => {
      if (err) return reject(err);
      resolve({ d: p.getPathTag().match(/d="([^"]+)"/)[1], w: p._luminanceData.width, h: p._luminanceData.height });
    });
  });
}

(async () => {
  const ink = await trace(inkPng);
  const sil = await trace(silPng, { turdSize: 200 });
  const open = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ink.w} ${ink.h}" width="${ink.w}" height="${ink.h}">\n` +
    '  <title>What If? question mark (black and white)</title>\n';
  const inkPath = `  <path id="ink" fill="#000" fill-rule="evenodd" d="${ink.d}"/>\n</svg>\n`;
  fs.writeFileSync(`${outBase}.svg`, open + `  <path id="fill" fill="#fff" fill-rule="evenodd" d="${sil.d}"/>\n` + inkPath);
  fs.writeFileSync(`${outBase}-lines.svg`, open + inkPath);

  const small = await trace(smallPng, { optTolerance: 0.4, turdSize: 8 });
  const tsFile = path.join(__dirname, '../../src/ui/questionMarkPath.ts');
  fs.writeFileSync(tsFile,
    '// Generated by tools/graphics/trace_question_bw.js — do not edit by hand.\n' +
    '// The hand-drawn question mark (assets/graphics/question-mark-bw-lines.svg) traced at\n' +
    '// one-third resolution: the ink only, as a single even-odd path, to draw with react-native-svg.\n' +
    `export const QUESTION_MARK_VIEWBOX = { width: ${small.w}, height: ${small.h} };\n` +
    `export const QUESTION_MARK_PATH =\n  '${small.d}';\n`);
  console.log('wrote', `${outBase}.svg`, `${outBase}-lines.svg`, tsFile);
})().catch(e => { console.error(e); process.exit(1); });
